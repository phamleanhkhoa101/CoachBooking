-- Existing trips and tickets are retained; unknown historical stops stay NULL.
CREATE TABLE stop_locations (
 location_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(200) NOT NULL, address VARCHAR(500) NOT NULL, area VARCHAR(200) NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE stop_templates (
 template_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(200) NOT NULL, company_id INTEGER NOT NULL REFERENCES bus_companies,
 route_id INTEGER NOT NULL REFERENCES routes, is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE template_stops (
 template_stop_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 template_id INTEGER NOT NULL REFERENCES stop_templates,
 location_id INTEGER NOT NULL REFERENCES stop_locations,
 stop_order INTEGER NOT NULL CHECK(stop_order >= 0),
 boarding BOOLEAN NOT NULL, dropoff BOOLEAN NOT NULL,
 offset_minutes INTEGER NOT NULL CHECK(offset_minutes >= 0),
 CHECK(boarding OR dropoff), UNIQUE(template_id, stop_order)
);
CREATE TABLE trip_stops (
 stop_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trip_id INTEGER NOT NULL REFERENCES trips ON DELETE CASCADE,
 location_id INTEGER NOT NULL REFERENCES stop_locations,
 stop_order INTEGER NOT NULL CHECK(stop_order >= 0),
 boarding BOOLEAN NOT NULL, dropoff BOOLEAN NOT NULL,
 name VARCHAR(200) NOT NULL, address VARCHAR(500) NOT NULL,
 scheduled_time TIMESTAMP NOT NULL,
 CHECK(boarding OR dropoff), UNIQUE(trip_id, stop_order)
);
ALTER TABLE tickets ADD COLUMN boarding_stop_id INTEGER REFERENCES trip_stops;
ALTER TABLE tickets ADD COLUMN dropoff_stop_id INTEGER REFERENCES trip_stops;
ALTER TABLE tickets ADD COLUMN boarding_name VARCHAR(200);
ALTER TABLE tickets ADD COLUMN boarding_address VARCHAR(500);
ALTER TABLE tickets ADD COLUMN boarding_time TIMESTAMP;
ALTER TABLE tickets ADD COLUMN dropoff_name VARCHAR(200);
ALTER TABLE tickets ADD COLUMN dropoff_address VARCHAR(500);
ALTER TABLE tickets ADD COLUMN dropoff_time TIMESTAMP;
CREATE TABLE trip_schedules (
 schedule_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(200) NOT NULL,
 vehicle_id INTEGER NOT NULL REFERENCES vehicles,
 route_id INTEGER NOT NULL REFERENCES routes,
 driver_id INTEGER NOT NULL REFERENCES drivers,
 template_id INTEGER NOT NULL REFERENCES stop_templates,
 departure_time TIME NOT NULL, weekdays VARCHAR(20) NOT NULL,
 valid_from DATE NOT NULL, valid_to DATE NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 excluded_dates TEXT NOT NULL DEFAULT '',
 last_result TEXT, last_run_at TIMESTAMP,
 CHECK(valid_to >= valid_from)
);
CREATE TABLE schedule_occurrences (
 occurrence_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id INTEGER NOT NULL REFERENCES trip_schedules,
 service_date DATE NOT NULL,
 trip_id INTEGER REFERENCES trips ON DELETE SET NULL,
 status VARCHAR(30) NOT NULL,
 UNIQUE(schedule_id, service_date)
);
CREATE INDEX idx_trip_stops_trip ON trip_stops(trip_id);
CREATE INDEX idx_trips_vehicle_interval ON trips(vehicle_id, departure_time, estimated_arrival_time);
CREATE INDEX idx_trips_driver_interval ON trips(driver_id, departure_time, estimated_arrival_time);

