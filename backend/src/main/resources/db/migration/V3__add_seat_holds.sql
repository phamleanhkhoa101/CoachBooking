CREATE TABLE seat_holds (
    hold_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_token   UUID NOT NULL,
    account_id   INTEGER NOT NULL REFERENCES accounts (account_id) ON DELETE CASCADE,
    trip_id      INTEGER NOT NULL REFERENCES trips (trip_id) ON DELETE CASCADE,
    seat_number  INTEGER NOT NULL CHECK (seat_number > 0),
    created_at   TIMESTAMP NOT NULL,
    expires_at   TIMESTAMP NOT NULL,
    CONSTRAINT uq_seat_holds_trip_seat UNIQUE (trip_id, seat_number)
);

CREATE INDEX idx_seat_holds_token ON seat_holds (hold_token);
CREATE INDEX idx_seat_holds_expiry ON seat_holds (expires_at);
CREATE INDEX idx_seat_holds_trip_expiry ON seat_holds (trip_id, expires_at);
