-- PostgreSQL Schema for Coach Booking System (English naming convention).
-- All business triggers are implemented in the Spring Boot service layer.

CREATE TABLE roles (
    role_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name   VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE accounts (
    account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50) NOT NULL UNIQUE,
    password   VARCHAR(100) NOT NULL,
    email      VARCHAR(100) NOT NULL UNIQUE,
    role_id    INTEGER NOT NULL REFERENCES roles (role_id),
    is_active  BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE employees (
    employee_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL CHECK (date_of_birth <= CURRENT_DATE - INTERVAL '18 years'),
    address       VARCHAR(100) NOT NULL,
    phone         VARCHAR(11) NOT NULL UNIQUE,
    gender        BOOLEAN NOT NULL DEFAULT FALSE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    account_id    INTEGER UNIQUE REFERENCES accounts (account_id)
);

CREATE TABLE customers (
    customer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    phone         VARCHAR(11) NOT NULL UNIQUE,
    gender        BOOLEAN NOT NULL DEFAULT FALSE,
    account_id    INTEGER UNIQUE REFERENCES accounts (account_id)
);

CREATE TABLE bus_companies (
    company_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(100) NOT NULL,
    phone        VARCHAR(15) NOT NULL UNIQUE,
    email        VARCHAR(100) NOT NULL UNIQUE,
    is_active    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE vehicle_types (
    type_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name     VARCHAR(100) NOT NULL,
    seat_capacity INTEGER NOT NULL CHECK (seat_capacity > 0),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE vehicles (
    vehicle_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    INTEGER NOT NULL REFERENCES bus_companies (company_id),
    type_id       INTEGER NOT NULL REFERENCES vehicle_types (type_id),
    license_plate VARCHAR(20) NOT NULL UNIQUE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE routes (
    route_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure          VARCHAR(255) NOT NULL,
    destination        VARCHAR(255) NOT NULL,
    distance           INTEGER CHECK (distance IS NULL OR distance > 0),
    estimated_duration TIME,
    is_active          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE ticket_prices (
    price_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL REFERENCES bus_companies (company_id),
    type_id    INTEGER NOT NULL REFERENCES vehicle_types (type_id),
    route_id   INTEGER NOT NULL REFERENCES routes (route_id),
    price      NUMERIC(12, 0) NOT NULL CHECK (price > 0),
    UNIQUE (company_id, type_id, route_id)
);

CREATE TABLE drivers (
    driver_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(100),
    date_of_birth  DATE NOT NULL CHECK (date_of_birth <= CURRENT_DATE - INTERVAL '18 years'),
    citizen_id     VARCHAR(12) NOT NULL UNIQUE,
    gender         BOOLEAN NOT NULL DEFAULT FALSE,
    phone          VARCHAR(11) NOT NULL UNIQUE,
    address        VARCHAR(100) NOT NULL,
    license_number VARCHAR(10) NOT NULL,
    issue_date     DATE NOT NULL,
    is_active      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE trips (
    trip_id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id             INTEGER NOT NULL REFERENCES vehicles (vehicle_id),
    route_id               INTEGER NOT NULL REFERENCES routes (route_id),
    driver_id              INTEGER NOT NULL REFERENCES drivers (driver_id),
    departure_time         TIMESTAMP NOT NULL,
    estimated_arrival_time TIMESTAMP,
    actual_price           NUMERIC(12, 0) CHECK (actual_price IS NULL OR actual_price >= 0),
    UNIQUE (vehicle_id, departure_time, driver_id)
);

CREATE TABLE invoices (
    invoice_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  INTEGER REFERENCES customers (customer_id),
    employee_id  INTEGER REFERENCES employees (employee_id),
    created_at   TIMESTAMP NOT NULL,
    total_amount NUMERIC(12, 0) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    is_paid      BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (customer_id IS NOT NULL OR employee_id IS NOT NULL)
);

CREATE TABLE payments (
    payment_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id     INTEGER NOT NULL UNIQUE REFERENCES invoices (invoice_id) ON DELETE CASCADE,
    amount         NUMERIC(12, 0) NOT NULL DEFAULT 0 CHECK (amount >= 0),
    payment_date   TIMESTAMP NOT NULL,
    payment_method VARCHAR(50) NOT NULL
);

CREATE TABLE tickets (
    ticket_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id     INTEGER NOT NULL REFERENCES trips (trip_id),
    invoice_id  INTEGER NOT NULL REFERENCES invoices (invoice_id) ON DELETE CASCADE,
    seat_number INTEGER NOT NULL CHECK (seat_number > 0),
    price       NUMERIC(12, 0) NOT NULL DEFAULT 0 CHECK (price >= 0),
    UNIQUE (trip_id, seat_number)
);

CREATE INDEX idx_vehicles_company ON vehicles (company_id);
CREATE INDEX idx_trips_departure_time ON trips (departure_time);
CREATE INDEX idx_trips_route ON trips (route_id);
CREATE INDEX idx_invoices_customer ON invoices (customer_id);
CREATE INDEX idx_invoices_created_at ON invoices (created_at);
CREATE INDEX idx_tickets_invoice ON tickets (invoice_id);
CREATE INDEX idx_tickets_trip ON tickets (trip_id);
