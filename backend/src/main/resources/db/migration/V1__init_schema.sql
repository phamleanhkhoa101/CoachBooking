-- Schema PostgreSQL cho hệ thống bán vé xe miền Đông (chuyển từ SQL Server).
-- Toàn bộ logic trigger cũ (tính giờ đến, giá vé, tổng tiền, trạng thái hóa đơn)
-- được chuyển vào tầng service của Spring Boot.

CREATE TABLE quyen (
    ma_quyen   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_quyen  VARCHAR(50) NOT NULL UNIQUE,
    mo_ta      VARCHAR(255)
);

CREATE TABLE tai_khoan (
    ma_tk         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_dang_nhap VARCHAR(50) NOT NULL UNIQUE,
    mat_khau      VARCHAR(100) NOT NULL,
    email         VARCHAR(100) NOT NULL UNIQUE,
    ma_quyen      INTEGER NOT NULL REFERENCES quyen (ma_quyen),
    trang_thai    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE nhan_vien (
    ma_nv     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_nv    VARCHAR(100) NOT NULL,
    nam_sinh  DATE NOT NULL CHECK (nam_sinh <= CURRENT_DATE - INTERVAL '18 years'),
    dia_chi   VARCHAR(100) NOT NULL,
    sdt       VARCHAR(11) NOT NULL UNIQUE,
    gioi_tinh BOOLEAN NOT NULL DEFAULT FALSE,
    trang_thai BOOLEAN NOT NULL DEFAULT TRUE,
    ma_tk     INTEGER UNIQUE REFERENCES tai_khoan (ma_tk)
);

CREATE TABLE khach_hang (
    ma_kh     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_kh    VARCHAR(100) NOT NULL,
    nam_sinh  DATE NOT NULL,
    sdt       VARCHAR(11) NOT NULL UNIQUE,
    gioi_tinh BOOLEAN NOT NULL DEFAULT FALSE,
    ma_tk     INTEGER UNIQUE REFERENCES tai_khoan (ma_tk)
);

CREATE TABLE nha_xe (
    ma_nx     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_nx    VARCHAR(100) NOT NULL,
    sdt       VARCHAR(15) NOT NULL UNIQUE,
    email     VARCHAR(100) NOT NULL UNIQUE,
    trang_thai BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE loai_xe (
    ma_lx     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_lx    VARCHAR(100) NOT NULL,
    so_cho    INTEGER NOT NULL CHECK (so_cho > 0),
    trang_thai BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE xe (
    ma_xe      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_nx      INTEGER NOT NULL REFERENCES nha_xe (ma_nx),
    ma_lx      INTEGER NOT NULL REFERENCES loai_xe (ma_lx),
    bien_so_xe VARCHAR(20) NOT NULL UNIQUE,
    trang_thai BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tuyen_duong (
    ma_tuyen           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diem_di            VARCHAR(255) NOT NULL,
    diem_den           VARCHAR(255) NOT NULL,
    quang_duong        INTEGER CHECK (quang_duong IS NULL OR quang_duong > 0),
    thoi_gian_du_kien  TIME,
    trang_thai         BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE gia_ve (
    ma_gv    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_nx    INTEGER NOT NULL REFERENCES nha_xe (ma_nx),
    ma_lx    INTEGER NOT NULL REFERENCES loai_xe (ma_lx),
    ma_tuyen INTEGER NOT NULL REFERENCES tuyen_duong (ma_tuyen),
    gia_ve   NUMERIC(12, 0) NOT NULL CHECK (gia_ve > 0),
    UNIQUE (ma_nx, ma_lx, ma_tuyen)
);

CREATE TABLE tai_xe (
    ma_tx     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_tx    VARCHAR(100),
    nam_sinh  DATE NOT NULL CHECK (nam_sinh <= CURRENT_DATE - INTERVAL '18 years'),
    cccd      VARCHAR(12) NOT NULL UNIQUE,
    gioi_tinh BOOLEAN NOT NULL DEFAULT FALSE,
    sdt       VARCHAR(11) NOT NULL UNIQUE,
    dia_chi   VARCHAR(100) NOT NULL,
    bang_lai  VARCHAR(5) NOT NULL,
    ngay_cap  DATE NOT NULL,
    trang_thai BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE chuyen_xe (
    ma_chuyen             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_xe                 INTEGER NOT NULL REFERENCES xe (ma_xe),
    ma_tuyen              INTEGER NOT NULL REFERENCES tuyen_duong (ma_tuyen),
    ma_tx                 INTEGER NOT NULL REFERENCES tai_xe (ma_tx),
    ngay_gio_khoi_hanh    TIMESTAMP NOT NULL,
    ngay_gio_den_du_kien  TIMESTAMP,
    gia_ve_thuc_te        NUMERIC(12, 0) CHECK (gia_ve_thuc_te IS NULL OR gia_ve_thuc_te >= 0),
    UNIQUE (ma_xe, ngay_gio_khoi_hanh, ma_tx)
);

CREATE TABLE hoa_don (
    ma_hd     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_kh     INTEGER REFERENCES khach_hang (ma_kh),
    ma_nv     INTEGER REFERENCES nhan_vien (ma_nv),
    ngay_lap  TIMESTAMP NOT NULL,
    tong_tien NUMERIC(12, 0) NOT NULL DEFAULT 0 CHECK (tong_tien >= 0),
    trang_thai BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (ma_kh IS NOT NULL OR ma_nv IS NOT NULL)
);

CREATE TABLE thanh_toan (
    ma_tt      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_hd      INTEGER NOT NULL UNIQUE REFERENCES hoa_don (ma_hd) ON DELETE CASCADE,
    tong_tien  NUMERIC(12, 0) NOT NULL DEFAULT 0 CHECK (tong_tien >= 0),
    ngay_tt    TIMESTAMP NOT NULL,
    phuong_thuc VARCHAR(50) NOT NULL
);

CREATE TABLE ve_xe (
    ma_ve     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_chuyen INTEGER NOT NULL REFERENCES chuyen_xe (ma_chuyen),
    ma_hd     INTEGER NOT NULL REFERENCES hoa_don (ma_hd) ON DELETE CASCADE,
    cho_ngoi  INTEGER NOT NULL CHECK (cho_ngoi > 0),
    gia_ve    NUMERIC(12, 0) NOT NULL DEFAULT 0 CHECK (gia_ve >= 0),
    UNIQUE (ma_chuyen, cho_ngoi)
);

CREATE INDEX idx_xe_ma_nx ON xe (ma_nx);
CREATE INDEX idx_chuyen_xe_khoi_hanh ON chuyen_xe (ngay_gio_khoi_hanh);
CREATE INDEX idx_chuyen_xe_ma_tuyen ON chuyen_xe (ma_tuyen);
CREATE INDEX idx_hoa_don_ma_kh ON hoa_don (ma_kh);
CREATE INDEX idx_hoa_don_ngay_lap ON hoa_don (ngay_lap);
CREATE INDEX idx_ve_xe_ma_hd ON ve_xe (ma_hd);
CREATE INDEX idx_ve_xe_ma_chuyen ON ve_xe (ma_chuyen);
